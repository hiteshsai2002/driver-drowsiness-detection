def predict_drowsiness(video_path):                         # Create a function that receives a video filename

    cap = cv2.VideoCapture(video_path)                     # Open the video using OpenCV

    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))  # Get the total number of frames

    frame_indices = np.linspace(                         # Select frames evenly throughout the video
        0,                                                # Start at the first frame
        total_frames - 1,                                 # End at the last frame
        300,                                              # Select 300 frames
        dtype=int                                          # Convert frame positions to integers
    )

    frames = []                                           # Create an empty list to store the frames

    for frame_index in frame_indices:                    # Go through each selected frame

        cap.set(cv2.CAP_PROP_POS_FRAMES, frame_index)    # Move to the selected frame

        success, frame = cap.read()                      # Read the frame

        if success:                                      # Continue if the frame was read successfully

            frame = cv2.cvtColor(                        # Convert BGR to RGB
                frame,
                cv2.COLOR_BGR2RGB
            )

            frame = cv2.resize(                          # Resize the frame to 64 × 64
                frame,
                (64, 64)
            )

            frames.append(frame)                         # Add the processed frame to the list

    cap.release()                                        # Close the video

    frames = np.array(frames, dtype=np.float32)           # Convert frames into a NumPy array

    frames = frames / 255.0                              # Normalize pixel values from 0-255 to 0-1

    predictions = loaded_model.predict(frames, verbose=0) # Ask the trained CNN to predict each frame

    predicted_classes = np.argmax(predictions, axis=1)   # Select the highest-probability class for each frame

    final_prediction = np.bincount(predicted_classes).argmax()  # Find the most common prediction

    class_names = {                                      # Define the three CNN classes
        0: "Alert",                                      # Class 0 means Alert
        1: "Low Vigilance",                              # Class 1 means Low Vigilance
        2: "Drowsy"                                      # Class 2 means Drowsy
    }

    return class_names[final_prediction]                 # Return the final video prediction

