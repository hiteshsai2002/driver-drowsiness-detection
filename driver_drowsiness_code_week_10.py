import cv2
import numpy as np

IMAGE_SIZE = 64
FRAMES_PER_VIDEO = 300

# Combine all uploaded videos
all_videos = video_files + more_video_files

# Store frames and labels
X_all = []
y_all = []

# Labels:
# 0 = Alert
# 5 = Low Vigilance
# 10 = Drowsy

video_labels = {
    "0.mp4": 0,
    "5.mp4": 5,
    "10.mp4": 10
}

for video in all_videos:

    print("\nProcessing:", video)

    cap = cv2.VideoCapture(video)

    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))

    # Select 300 frames evenly throughout the video
    frame_indices = np.linspace(
        0,
        total_frames - 1,
        FRAMES_PER_VIDEO,
        dtype=int
    )

    frames = []

    for frame_index in frame_indices:

        cap.set(cv2.CAP_PROP_POS_FRAMES, frame_index)

        success, frame = cap.read()

        if success:

            frame = cv2.resize(
                frame,
                (IMAGE_SIZE, IMAGE_SIZE)
            )

            frame = cv2.cvtColor(
                frame,
                cv2.COLOR_BGR2RGB
            )

            frames.append(frame)

    cap.release()

    # Convert frames to NumPy array
    frames = np.array(frames, dtype=np.float32)

    # Normalize pixels
    frames = frames / 255.0

    # Get label from filename
    filename = video.split("/")[-1]

    label = video_labels[filename]

    # Add frames and labels
    X_all.extend(frames)
    y_all.extend([label] * len(frames))

    print("Frames extracted:", len(frames))
    print("Label:", label)