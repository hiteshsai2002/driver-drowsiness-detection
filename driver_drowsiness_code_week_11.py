IMAGE_SIZE = 64                                 # Set each extracted frame to 64 × 64 pixels
FRAMES_PER_VIDEO = 300                          # Extract 300 frames from each video

all_videos = video_files + more_video_files     # Combine the videos from Step 1 and Step 7 into one list

X_all = []                                      # Create an empty list to store frames from all videos
y_all = []                                      # Create an empty list to store labels for all frames

video_labels = {                                # Create a dictionary connecting video filenames to labels
    "0.mp4": 0,                                 # 0.mp4 is assigned label 0 (Alert)
    "5.mp4": 5,                                 # 5.mp4 is assigned label 5 (Low Vigilance)
    "10.mp4": 10                                # 10.mp4 is assigned label 10 (Drowsy)
}

for video in all_videos:                        # Process each video in the combined video list

    print("\nProcessing:", video)               # Display the name of the video currently being processed

    cap = cv2.VideoCapture(video)               # Open the current video using OpenCV

    total_frames = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))  # Get the total number of frames in the video

    frame_indices = np.linspace(                # Generate frame positions evenly throughout the video
        0,                                      # Start from the first frame
        total_frames - 1,                       # End at the last frame
        FRAMES_PER_VIDEO,                       # Select 300 frame positions
        dtype=int                               # Convert frame positions to integers
    )

    frames = []                                 # Create an empty list to store frames from the current video

    for frame_index in frame_indices:           # Go through each selected frame position

        cap.set(cv2.CAP_PROP_POS_FRAMES, frame_index)  # Move to the selected frame

        success, frame = cap.read()             # Read the selected frame

        if success:                             # Continue only if the frame was successfully read

            frame = cv2.resize(                  # Resize the frame to the CNN input size
                frame,
                (IMAGE_SIZE, IMAGE_SIZE)
            )

            frame = cv2.cvtColor(                # Convert the frame from BGR to RGB
                frame,
                cv2.COLOR_BGR2RGB
            )

            frames.append(frame)                # Add the processed frame to the current video's frame list

    cap.release()                               # Close the current video and release OpenCV resources

    frames = np.array(frames, dtype=np.float32) # Convert the current video's frames into a NumPy array

    frames = frames / 255.0                     # Normalize pixel values from 0-255 to 0-1

    filename = video.split("/")[-1]             # Extract only the filename from the video path

    label = video_labels[filename]              # Look up the correct label using the filename

    X_all.extend(frames)                        # Add all extracted frames to the complete dataset

    y_all.extend([label] * len(frames))         # Add the same label for every frame from this video

    print("Frames extracted:", len(frames))     # Display the number of frames extracted from this video

    print("Label:", label)                      # Display the label assigned to this video

